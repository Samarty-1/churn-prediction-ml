"""Generate the interim README from measured staging results."""

import json
from pathlib import Path


def render_readme(report: dict, development: dict | None = None) -> str:
    labels = {
        "sheet_overlap": "Repeated sheet overlap",
        "exact_duplicate": "Exact duplicate copies",
        "bad_debt_adjustment": "Bad-debt adjustments",
        "non_product": "Non-product codes",
        "cancellation": "Product cancellations",
        "stock_adjustment": "Nonpositive price or quantity",
        "missing_customer": "Otherwise valid sales missing customer ID",
        "sale": "Retained identified sales",
    }
    rows = "\n".join(
        f"| {labels[item['step']]} | {item['rows']:,} | {item['signed_amount_gbp']} |"
        for item in report["waterfall"]
    )
    status = "Stopped at the cleaning checkpoint. No evaluation snapshots constructed."
    if development is not None:
        cutoff_rows = "\n".join(
            f"| {r['cutoff']} | {r['customers']:,} | {r['churned']:,} | "
            f"{r['churn_rate']:.6%} | {r['role']} |"
            for r in development["cutoffs"]
        )
        status = f"""Development labels and features are built; no models have been fitted.
Preregistration awaits approval before modelling. Every development cutoff passed
the exact feature-equality test after deleting all future sales and cancellations.

| Cutoff | Eligible customers | Churned | Churn rate | Role |
|---|---:|---:|---:|---|
{cutoff_rows}

Displayed rates use six decimal places; exact counts and unrounded rates are in
[development results](results/development_summary.json). Warm-up snapshots train
later origins; they are not silently presented as tested predictions.
Sealed cutoffs: {", ".join(development["sealed_cutoffs"])}.
Their populations, features, labels and base rates have not been constructed.
The access guard rejects these requests before database or snapshot access.
"""
    return f"""# churn-prediction-ml

**Real retail data staged and reconciled. No model performance or profit claim yet.**

The previous version generated churn labels from a hand-written logistic formula,
then fitted models to recover that formula. Its winning model and contract-risk
insight were circular, not evidence about real customers. The original is
preserved at `v0-synthetic`.

## What survived cleaning

The source has {report["raw_rows"]:,} invoice lines. Cleaning retains
{report["customers"]:,} identified customers and {report["orders"]:,} sale invoices.
The table is an exhaustive, mutually exclusive waterfall; the final row is retained.
Amounts are exact signed GBP values, without rounding before aggregation.

| Disposition | Rows | Signed amount (GBP) |
|---|---:|---:|
{rows}

Excluding missing customer IDs drops GBP {report["missing_customer_sale_revenue_gbp"]}
of otherwise valid gross product sales, from GBP {report["eligible_product_sale_revenue_gbp"]}.
Retained gross product-sales revenue is GBP {report["retained_sale_revenue_gbp"]}.
These are sales amounts before cancellation netting, not margin or profit.

One difference from the earlier retail SQL: {report["positive_price_rounds_to_zero_rows"]}
positive-price lines (GBP {report["positive_price_rounds_to_zero_amount_gbp"]} total)
would become zero-price adjustments if unit prices were first rounded to pennies.
They remain sales here under the positive-price rule frozen in preregistration.

Source: [UCI Online Retail II](https://doi.org/10.24432/C5CG6D).
Measured outputs: [cleaning summary](results/cleaning_summary.json) and
[source digests](results/ingest_manifest.json). See [data rules](docs/DATA.md).
This README is generated by `churn.report`; the fixture suite checks it against the results.

## Evaluation status

{status}

Baselines, models, calibration and confidence intervals remain pending.
The full public source was read for cleaning; the seal protects evaluation access
through the pipeline, not raw-file secrecy against deliberate code changes.

The intended question is whether retention targeting beats simple recency, RFM
and customer-base-model rules. See [preregistration](docs/PREREGISTRATION.md),
[trial ledger](docs/TRIALS.md) and [phase boundaries](docs/PHASES.md).

## Limitations already visible

This is historical gift-wholesaler transaction data, with seasonal demand,
unidentified buyers and cancellations that do not identify their original sale.
Exact repeated lines are treated as double scans. Bulk billing reversals can
inflate gross customer value. The data contains no treatment assignment or
retention offers: any future save rate is an assumption, not measured uplift.

## Reproduce the implemented phase

Use a project virtual environment, never the base Anaconda environment:

```powershell
py -3.11 -m venv .venv
.venv/Scripts/python.exe -m pip install -c requirements-lock.txt -e '.[dev]'
.venv/Scripts/python.exe -m churn run-all
.venv/Scripts/python.exe -m pytest -q
.venv/Scripts/python.exe -m ruff check .
```

Run from the repository root. The pipeline downloads the original workbook,
lands Parquet, stages with DuckDB SQL, checks contracts and writes `results/`.
It stops before modelling. Use `python -m churn stage` to rerun cleaning SQL,
or `python -m churn build-development` to rebuild development snapshots from
staged Parquet. Tests do not download the full dataset.
Data, models and virtual environments are ignored by Git.

Code: [MIT](LICENSE). Source data: CC BY under the UCI license.
"""


def write_readme(root: Path):
    report = json.loads((root / "results/cleaning_summary.json").read_text())
    development_path = root / "results/development_summary.json"
    development = json.loads(development_path.read_text()) if development_path.exists() else None
    (root / "README.md").write_text(render_readme(report, development), encoding="utf-8")
